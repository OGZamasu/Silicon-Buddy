    @Test
    fun `a pair response without a scope means full`() {
        val paired = json.decodeFromString<PairResponse>(
            """{"deviceID":"1","token":"t","macName":"Mac","port":8788}""",
        )
        assertNull(paired.scope)
        assertEquals(DeviceScope.Full, DeviceScope.from(paired.scope))
    }
