    @Test
    fun `a conversation conflict is its own case`() {
        val body = part("POST__conversations__id__messages", "errors.409").toString()
        assertTrue(
            TransportError.from(409, body, "/conversations/1/messages")
                is TransportError.Conflict,
        )
    }

    @Test
    fun `the body limit the Mac states is the one this app enforces`() {
        val body = part("POST__chat", "errors.413").toString()
        val error = TransportError.from(413, body, "/chat")
        assertTrue(error is TransportError.TooLarge)
        // The Mac says 4194304 bytes; the app refuses before sending that much.
        assertTrue(error!!.message!!.contains("4194304"))
        assertEquals(4 * 1024 * 1024, SendLimits.MAX_BODY_BYTES)
    }

