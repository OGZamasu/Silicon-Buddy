    // MARK: - Errors

    @Test
    fun `every error body in the contract decodes and maps`() {
        val directory = File(javaClass.classLoader!!.getResource("GET__health.json")!!.toURI())
            .parentFile
        var checked = 0
        directory.listFiles { file -> file.extension == "json" }!!.forEach { file ->
            val fields = Json.parseToJsonElement(file.readText()) as JsonObject
            val errors = fields["errors"] as? JsonObject ?: return@forEach
            for ((status, body) in errors) {
                val decoded = json.decodeFromString<ErrorResponse>(body.toString())
                assertTrue("${file.name} $status has an empty message", decoded.error.isNotEmpty())
                assertNotNull(
                    "$status should map to an error",
                    TransportError.from(status.toInt(), body.toString(), "/x"),
                )
                checked++
            }
        }
        assertTrue("Every route lists the errors it can answer", checked > 30)
    }

    @Test
    fun `the scope refusal is not an unpairing`() {
        val body = part("POST__load", "errors.403").toString()
        val error = TransportError.from(403, body, "/load")
        assertTrue(error is TransportError.Forbidden)
        assertTrue(error!!.message!!.contains("chat only"))
    }

    @Test
    fun `a conversation conflict is its own case`() {
        val body = part("POST__conversations__id__messages", "errors.409").toString()
        assertTrue(
            TransportError.from(409, body, "/conversations/1/messages")
                is TransportError.Conflict,
        )
    }

    @Test
    fun `the body limit the Mac states is the one this app enforces`() {
        val body = part("POST__chat", "errors.413").toString()
        val error = TransportError.from(413, body, "/chat")
        assertTrue(error is TransportError.TooLarge)
        // The Mac says 4194304 bytes; the app refuses before sending that much.
        assertTrue(error!!.message!!.contains("4194304"))
        assertEquals(4 * 1024 * 1024, SendLimits.MAX_BODY_BYTES)
    }

    // MARK: - Requests this app builds

    @Test
    fun `requests encode the way the Mac reads them`() {
        val fields = Json.parseToJsonElement(
            json.encodeToString(LoadRequest("bonsai-2-27b", "PTQ1_0")),
        ) as JsonObject
        assertEquals("bonsai-2-27b", (fields["modelID"] as JsonPrimitive).content)
        assertNull("Absent options must not be sent as null", fields["contextLength"])
    }

    @Test
    fun `a new message carries content, not a transcript`() {
        val request = NewMessageRequest(
            content = "What is this?",
            images = listOf("data:image/jpeg;base64,AAA"),
            maxTokens = 2048,
        )
        val fields = Json.parseToJsonElement(json.encodeToString(request)) as JsonObject
        assertEquals("What is this?", (fields["content"] as JsonPrimitive).content)
        assertEquals(1, (fields["images"] as JsonArray).size)
        assertEquals("2048", (fields["maxTokens"] as JsonPrimitive).content)
        assertNull("The Mac has the history; this route takes one message", fields["messages"])
    }

    @Test
    fun `an empty image list is still sent`() {
        val request = ChatRequest(listOf(ChatMessageWire("user", "hi")))
        val message = ((Json.parseToJsonElement(json.encodeToString(request)) as JsonObject)
            .getValue("messages") as JsonArray)[0] as JsonObject
        assertEquals(0, (message["images"] as JsonArray).size)
    }

