/**
 * The mirrored types, checked against the Mac's own export.
 *
 * `contract/` is generated by silicon-optimizer's ContractExportTests — the shapes its
 * wire types actually encode. Each file holds a route: its request, its response, the
 * events it can send and the errors it can answer. The round trip is the part that
 * matters: decode, re-encode, compare the JSON. A field this app forgot to mirror
 * disappears in the re-encode, so the comparison fails.
 */
class ContractTest {

    private val json = Json {
        ignoreUnknownKeys = true
        explicitNulls = false
        encodeDefaults = true
    }

    private fun fixture(name: String): JsonObject {
        val text = javaClass.classLoader?.getResourceAsStream("$name.json")?.bufferedReader()
            ?.readText() ?: error("Missing fixture $name.json — run contract/refresh.sh")
        return Json.parseToJsonElement(text) as JsonObject
    }

    private fun part(name: String, part: String): JsonElement {
        val fields = fixture(name)
        return when {
            part.startsWith("events.") ->
                (fields["events"] as JsonObject).getValue(part.removePrefix("events."))
            part.startsWith("errors.") ->
                (fields["errors"] as JsonObject).getValue(part.removePrefix("errors."))
            else -> fields.getValue(part)
        }
    }

    private inline fun <reified T> roundTrip(name: String, part: String = "response"): T {
        val piece = part(name, part)
        val decoded = json.decodeFromString<T>(piece.toString())
        val reencoded = json.encodeToString(decoded)
        assertEquals(
            "$name.$part changed shape on a round trip",
            decoded,
            json.decodeFromString<T>(reencoded),
        )
        val differences = difference(strip(piece), strip(Json.parseToJsonElement(reencoded)))
        assertTrue(
            "$name.$part lost or changed fields on a round trip:\n" +
                differences.joinToString("\n"),
            differences.isEmpty(),
        )
        return decoded
    }

    private fun strip(element: JsonElement): JsonElement = when (element) {
        is JsonObject -> JsonObject(
            element.filterValues { it !is JsonNull }.mapValues { strip(it.value) },
        )
        is JsonArray -> JsonArray(element.map { strip(it) })
        else -> element
    }

    private fun difference(mine: JsonElement, theirs: JsonElement, path: String = ""): List<String> =
        when {
            mine is JsonObject && theirs is JsonObject ->
                (mine.keys + theirs.keys).sorted().flatMap { key ->
                    val childPath = if (path.isEmpty()) key else "$path.$key"
                    val a = mine[key]
                    val b = theirs[key]
                    when {
                        a == null -> listOf("+ $childPath appeared after the round trip")
                        b == null -> listOf("- $childPath was lost — is it mirrored?")
                        else -> difference(a, b, childPath)
                    }
                }
            mine is JsonArray && theirs is JsonArray ->
                if (mine.size != theirs.size) {
                    listOf("$path has ${mine.size} items, round trip has ${theirs.size}")
                } else {
                    mine.indices.flatMap { difference(mine[it], theirs[it], "$path[$it]") }
                }
            mine is JsonPrimitive && theirs is JsonPrimitive -> {
                val a = mine.doubleOrNull
                val b = theirs.doubleOrNull
                val same = if (a != null && b != null) a == b else mine.content == theirs.content
                if (same) emptyList() else listOf("$path: $mine != $theirs")
            }
            else -> if (mine == theirs) emptyList() else listOf("$path: $mine != $theirs")
        }

